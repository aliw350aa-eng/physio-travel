function run() {
  if (db.prepare('SELECT 1 FROM doctors WHERE demo=1 LIMIT 1').get()) return;
  const t = Date.now();
  const ins = db.transaction(() => {
    // حسابات مرضى وهمية لتقييمات النماذج (مفيش كلمة سر، فمفيش حد يقدر يدخل بيها)
    const pat = [1, 2, 3].map((i) => db.prepare('INSERT INTO users(email,name,role,created_at) VALUES(?,?,?,?)')
      .run('demo-patient-' + i + '@demo.invalid', 'مريض نموذج ' + i, 'patient', t).lastInsertRowid);
    DEMO.forEach((d, i) => {
      const uid = db.prepare('INSERT INTO users(email,name,role,created_at) VALUES(?,?,?,?)')
        .run('demo-doctor-' + (i + 1) + '@demo.invalid', d.name, 'doctor', t).lastInsertRowid;
      const prices = {};
      d.types.forEach((k) => { prices[k] = Math.round(T[k] * d.level / 10) * 10; });
      const cov = Object.keys(d.cov).map((c) => ({ c, f: d.cov[c] }));
      db.prepare(`INSERT INTO doctors(user_id,name,title,years,bio,types,prices,cov,modes,slots,clinic_addr,published,demo,updated_at)
        VALUES(?,?,?,?,?,?,?,?,?,?,?,1,1,?)`).run(uid, d.name, d.title, d.years, d.bio, JSON.stringify(d.types), JSON.stringify(prices),
        JSON.stringify(cov), JSON.stringify(['home', 'clinic']), JSON.stringify(ALL), 'عيادة نموذج، ' + cov[0].c, t);
      d.rv.forEach((r, j) => {
        db.prepare('INSERT INTO reviews(doctor_id,patient_id,name,stars,text,created_at) VALUES(?,?,?,?,?,?)')
          .run(uid, pat[j], r[0], r[1], r[2], t - (j + 1) * 7 * 86400000);
      });
    });
  });
  ins();
  console.log('تمت إضافة ' + DEMO.length + ' أطباء نموذج.');
}

module.exports = { run };
if (require.main === module) run();
